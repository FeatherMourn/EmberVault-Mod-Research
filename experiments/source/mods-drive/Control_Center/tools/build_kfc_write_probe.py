"""Build a small, reversible scalar write/readback/revert EML probe."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RESULTS = ROOT / "research" / "kfc_probe_results_1076226.json"
DEFAULT_MANIFEST = ROOT / "research" / "probes" / "kfc_read_probe_1076226" / "probe_manifest.json"
DEFAULT_OUT = ROOT / "research" / "probes" / "kfc_write_probe_batch1"
ALLOWED_RESOURCES = (
    "keen::BalancingTable",
    "keen::ecs::GameSettings",
    "keen::ItemInfo",
    "keen::BuffType",
    "keen::TerraformingEfficiencyRegistryResource",
)


def quote(value: str) -> str:
    return value.replace("\\", "\\\\").replace("'", "\\'")


def choose(results: dict, manifest: dict, limit: int, skip: set[str] | None = None) -> list[dict]:
    skip = skip or set()
    candidates = {(x["target_resource"], x["target_field"]): x for x in manifest.get("candidates", [])}
    selected = []
    for key, result in sorted(results.get("results", {}).items()):
        resource, field = key.rsplit(".", 1)
        if resource not in ALLOWED_RESOURCES or not result.get("readable"):
            continue
        if key in skip:
            continue
        samples = result.get("samples", [])
        kind = samples[0].get("type") if samples else None
        if kind not in {"number", "boolean"}:
            continue
        candidate = candidates.get((resource, field))
        if candidate:
            sample = samples[0].get("value")
            observed_kind = "integer" if kind == "number" and str(sample).lstrip("-").isdigit() else kind
            selected.append({**candidate, "observed_type": observed_kind, "sample": sample})
        if len(selected) >= limit:
            break
    return selected


def lua(candidates: list[dict], build: str) -> str:
    lines = [
        "-- Generated by Enshrouded Control Center KFC Research Lab.",
        "-- Reversible scalar write/readback/revert probe.",
        f"local BUILD = '{quote(build)}'",
        "local function log(result) print('[CC-WRITE-RESEARCH] ' .. result) end",
        "local function test(resource_name, field_name, candidate_id, kind)",
        "    local ok, resources = pcall(function() return game.assets.get_resources_by_type(resource_name) or {} end)",
        "    if not ok or #resources == 0 then log(candidate_id .. '|resource_not_loaded'); return end",
        "    local resource = resources[1]",
        "    local read_ok, original = pcall(function() return resource.data[field_name] end)",
        "    if not read_ok then log(candidate_id .. '|read_error|' .. tostring(original)); return end",
        "    local test_value = original",
        "    if kind == 'boolean' then test_value = not original end",
        "    if kind == 'number' then test_value = original + 0.125 end",
        "    if kind == 'integer' then test_value = original + 1 end",
        "    local write_ok, write_error = pcall(function() resource.data[field_name] = test_value end)",
        "    if not write_ok then log(candidate_id .. '|write_error|' .. tostring(write_error)); return end",
        "    local readback_ok, readback = pcall(function() return resource.data[field_name] end)",
        "    local restore_ok, restore_error = pcall(function() resource.data[field_name] = original end)",
        "    local restored_ok, restored = pcall(function() return resource.data[field_name] end)",
        "    log(table.concat({candidate_id, 'write=' .. tostring(write_ok), 'readback=' .. tostring(readback_ok), tostring(readback), 'restore=' .. tostring(restore_ok), 'restored=' .. tostring(restored_ok), tostring(restored)}, '|'))",
        "    if not restore_ok then log(candidate_id .. '|restore_error|' .. tostring(restore_error)) end",
        "end",
        "log('BEGIN|build=' .. BUILD)",
    ]
    for item in candidates:
        lines.append("test('%s', '%s', '%s', '%s')" % (quote(item["target_resource"]), quote(item["target_field"]), quote(f"{item['target_resource']}.{item['target_field']}"), item["observed_type"]))
    lines.append("log('END|build=' .. BUILD)")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--limit", type=int, default=20)
    parser.add_argument("--skip-manifest", type=Path, default=None)
    args = parser.parse_args()
    results = json.loads(args.results.read_text(encoding="utf-8"))
    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    skip = set()
    if args.skip_manifest and args.skip_manifest.is_file():
        skip = {f"{x['target_resource']}.{x['target_field']}" for x in json.loads(args.skip_manifest.read_text(encoding="utf-8")).get("candidates", [])}
    candidates = choose(results, manifest, args.limit, skip)
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "src").mkdir(parents=True, exist_ok=True)
    build = str(results.get("build", "unknown"))
    batch_id = args.output.name.lower().replace("-", "_")
    mod_id = f"control_center_{batch_id}"
    (args.output / "mod.json").write_text(json.dumps({"id": mod_id, "name": f"Control Center {batch_id}", "version": "0.1.0", "author": "Enshrouded Control Center", "capabilities": ["patch"], "feature_state": "research-only", "entrypoint": "src/mod.lua", "research_build": build, "mode": "reversible_scalar_write", "candidate_count": len(candidates)}, indent=2) + "\n", encoding="utf-8")
    (args.output / "src" / "mod.lua").write_text(lua(candidates, build), encoding="utf-8")
    (args.output / "probe_manifest.json").write_text(json.dumps({"build": build, "mode": "reversible_scalar_write", "candidates": candidates}, indent=2) + "\n", encoding="utf-8")
    print(f"Generated reversible write probe with {len(candidates)} candidates: {args.output}")


if __name__ == "__main__":
    main()
