"""Build a one-field behavior probe that intentionally leaves the test value active."""
from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def q(value: str) -> str:
    return value.replace("\\", "\\\\").replace("'", "\\'")


parser = argparse.ArgumentParser()
parser.add_argument("--resource", required=True)
parser.add_argument("--field", required=True)
parser.add_argument("--value", required=True)
parser.add_argument("--name", required=True)
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()

args.output.mkdir(parents=True, exist_ok=True)
(args.output / "src").mkdir(parents=True, exist_ok=True)
mod_id = "control_center_behavior_" + args.name.lower().replace("-", "_").replace(" ", "_")
lua = f'''-- Generated by Enshrouded Control Center behavior research.
local resource_name = '{q(args.resource)}'
local field_name = '{q(args.field)}'
local test_value = {args.value}
local ok, resources = pcall(function() return game.assets.get_resources_by_type(resource_name) or {{}} end)
if not ok or #resources == 0 then
    print('[CC-BEHAVIOR] ' .. resource_name .. '.' .. field_name .. '|resource_not_loaded')
else
    local resource = resources[1]
    local read_ok, original = pcall(function() return resource.data[field_name] end)
    local write_ok, write_error = pcall(function() resource.data[field_name] = test_value end)
    local verify_ok, applied = pcall(function() return resource.data[field_name] end)
    print('[CC-BEHAVIOR] ' .. resource_name .. '.' .. field_name .. '|original=' .. tostring(original) .. '|write=' .. tostring(write_ok) .. '|applied=' .. tostring(applied) .. '|verify=' .. tostring(verify_ok))
    if not write_ok then print('[CC-BEHAVIOR] error=' .. tostring(write_error)) end
end
'''
(args.output / "src" / "mod.lua").write_text(lua, encoding="utf-8")
(args.output / "mod.json").write_text(json.dumps({"id": mod_id, "name": "Control Center Behavior - " + args.name, "version": "0.1.0", "author": "Enshrouded Control Center", "capabilities": ["patch"], "feature_state": "research-only", "entrypoint": "src/mod.lua", "mode": "behavior_test", "resource": args.resource, "field": args.field, "test_value": args.value}, indent=2) + "\n", encoding="utf-8")
print(f"Generated {mod_id} at {args.output}")
