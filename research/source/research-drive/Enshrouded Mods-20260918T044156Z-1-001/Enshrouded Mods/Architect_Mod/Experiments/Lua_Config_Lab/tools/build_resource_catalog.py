def main() -> int:
    known = load_known_roots()
    roots = known["roots"]
    family_to_root = {r["family"]: r for r in roots}

    entries = []
    seen_families = set()
    for category, items in CATALOG:
        assert category in CATEGORIES, "bad category %r" % category
        for family, friendly, desc, tags, access in items:
            if family not in family_to_root:
                raise SystemExit("curated family not in known roots: %s" % family)
            if family in seen_families:
                raise SystemExit("duplicate family in curated table: %s" % family)
            seen_families.add(family)
            root = family_to_root[family]
            entries.append({
                "resource_type": root["resource_type"],
                "family": family,
                "friendly_name": friendly,
                "primary_category": category,
                "description": desc,
                "tags": tags,
                "access_level": access,
                "friendly_controls_available": False,
            })

    missing = set(family_to_root) - seen_families
    if missing:
        raise SystemExit("families not covered by curated table: %s" % sorted(missing))
    if len(entries) != len(roots):
        raise SystemExit("entry count %d != root count %d" % (len(entries), len(roots)))

    out_path = os.path.join(PKG, "architect_lua_config_lab", "data", "resource_catalog.json")
    payload = {
        "schema": "architect_lua_config_lab.resource_catalog.v1",
        "categories": CATEGORIES,
        "count": len(entries),
        "entries": entries,
    }
    with open(out_path, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2, ensure_ascii=False)
        handle.write("\n")
    print("wrote %s (%d entries)" % (out_path, len(entries)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
