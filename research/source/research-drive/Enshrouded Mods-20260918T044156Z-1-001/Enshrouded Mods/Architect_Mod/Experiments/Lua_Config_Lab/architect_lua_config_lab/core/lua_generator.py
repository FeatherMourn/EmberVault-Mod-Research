# ---------------------------------------------------------------------------
# Lua literal serializers
# ---------------------------------------------------------------------------


def lua_string(value: Any) -> str:
    """Emit a Lua string literal, escaping quotes, backslashes and control chars."""
    text = value if isinstance(value, str) else str(value)
    out = []
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif code < 32 or code == 127:
            out.append("\\%03d" % code)  # Lua decimal escape
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def lua_number(value: Any, kind: str = "") -> str:
    """Emit a numeric literal from a *parsed* numeric value.

    ``kind`` is the schema kind (``u32``, ``f32``, ...) used to choose integer
    vs float representation.
    """
    if isinstance(value, bool):
        raise ValueError("cannot emit a boolean as a number")
    if kind in ("f16", "f32", "f64"):
        number = float(value)
        if not math.isfinite(number):
            raise ValueError("refusing to emit a non-finite float %r" % value)
        text = repr(number)
        if "." not in text and "e" not in text and "E" not in text:
            text += ".0"
        return text
    # integer kinds and fallback
    if isinstance(value, float):
        if not value.is_integer():
            raise ValueError("refusing to emit non-integer %r as integer" % value)
        value = int(value)
    if not isinstance(value, int):
        raise ValueError("refusing to emit non-numeric value %r" % value)
    return str(value)


def lua_bool(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    raise ValueError("cannot emit %r as a boolean" % value)


def lua_literal(value: Any, schema_type: str = "") -> str:
    """Emit a Lua literal for a value given its schema type.

    Values are expected to have been parsed/validated already; this function
    never pastes raw untrusted strings into the output.
    """
    if schema_type == "bool":
        return lua_bool(value)
    if schema_type in ("f16", "f32", "f64"):
        return lua_number(value, schema_type)
    if schema_type in ("u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64"):
        return lua_number(value, schema_type)
    # string, enum, guid, reference -> string literal
    return lua_string(value)


def lua_path_table(components: List[PathComponent]) -> str:
    """Emit a Lua array literal representing a field path.

    String components become string literals, index components become integer
    literals. Example: ``{"gliderConfig", "accelerationForward"}`` or
    ``{"values", 1}``.
    """
    parts = []
    for component in components:
        if component.kind == "field":
            parts.append(lua_string(component.name))
        else:
            parts.append(str(component.index or 0))
    return "{ " + ", ".join(parts) + " }"


