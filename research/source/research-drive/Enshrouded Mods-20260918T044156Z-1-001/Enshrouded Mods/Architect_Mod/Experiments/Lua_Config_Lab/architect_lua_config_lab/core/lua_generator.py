"""Lua generation.

Generates the ``src/mod.lua`` body for a startup EML patch mod. The output is
deterministic for identical input (no random GUIDs or timestamps in the body).

Generated Lua:

* resolves the requested resource type through ``game.assets``,
* validates resource selection (FIRST / ALL / MATCH),
* navigates the requested field path,
* optionally compares an expected original value (build-update protection),
* applies the replacement value,
* records diagnostics via ``print`` and ``io.export``.

It never performs live process modification and never invents missing
resources/fields.
"""

