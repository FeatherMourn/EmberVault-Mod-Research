_HEADER = """-- Generated by Architect Lua Config Lab
-- Startup resource configuration mod (EML/Lua backend only).
-- This file is generated; do not hand-edit. See profile.json for source.
"""


_LUA_TEMPLATE = _HEADER + """
print(@@MOD_NAME@@ .. " loaded!")

-- ============================================================
-- Startup resource edits (generated, deterministic)
-- ============================================================

local EDITS = @@EDITS_BLOCK@@

-- ============================================================
-- Shared helpers
-- ============================================================

local function lua_string(value)
    local s = tostring(value or "")
    s = string.gsub(s, "\\", "\\\\")
    s = string.gsub(s, '"', '\\"')
    s = string.gsub(s, "\r", "\\r")
    s = string.gsub(s, "\n", "\\n")
    s = string.gsub(s, "\t", "\\t")
    return s
end

local function path_string(path)
    local parts = {}
    for _, part in ipairs(path) do
        if type(part) == "number" then
            parts[#parts] = parts[#parts] .. "[" .. tostring(part) .. "]"
        else
            table.insert(parts, tostring(part))
        end
    end
    return table.concat(parts, ".")
end

local function read_path(root, path)
    local current = root
    for i = 1, #path do
        local part = path[i]
        if type(part) == "number" then
            current = current[part]
        else
            current = current[part]
        end
        if current == nil then
            return nil
        end
    end
    return current
end

local function write_path(root, path, value)
    local current = root
    for i = 1, #path - 1 do
        local part = path[i]
        if type(part) == "number" then
            current = current[part]
        else
            current = current[part]
        end
        if current == nil then
            return nil, "missing intermediate path element"
        end
    end
    local last = path[#path]
    if type(last) == "number" then
        current[last] = value
    else
        current[last] = value
    end
    return true
end

local function resolve_resources(edit)
    local ok, resources = pcall(function()
        return game.assets.get_resources_by_type(edit.resourceType)
    end)
    if not ok or not resources then
        return nil, "enumeration_failed"
    end
    if edit.mode == "first" then
        if #resources == 0 then
            return nil, "no_resources"
        end
        return { resources[1] }, nil
    elseif edit.mode == "all" then
        if #resources == 0 then
            return nil, "no_resources"
        end
        return resources, nil
    elseif edit.mode == "match" then
        local matches = {}
        for _, resource in ipairs(resources) do
            local current = read_path(resource.data, edit.selectorField)
            if current == edit.selectorValue then
                table.insert(matches, resource)
            end
        end
        if #matches == 0 then
            return nil, "selector_no_match"
        end
        if #matches > 1 then
            return nil, "selector_multiple_matches"
        end
        return matches, nil
    end
    return nil, "unknown_target_mode"
end

local function apply_one(edit, resource, result)
    local ok, err = pcall(function()
        local current = read_path(resource.data, edit.path)
        if current == nil then
            error("field path not present")
        end
        if edit.hasExpected then
            if current ~= edit.expected then
                error("precondition mismatch")
            end
        end
        write_path(resource.data, edit.path, edit.value)
        local readback = read_path(resource.data, edit.path)
        if readback ~= edit.value then
            error("readback mismatch")
        end
    end)
    if not ok then
        result.status = "error"
        result.error = tostring(err or "")
        return false
    end
    result.status = "applied"
    return true
end

local function run()
    local status = {
        schema = "architect.lua_config_lab.v1",
        profile = @@PROFILE_NAME@@,
        gameVersion = tostring(game.version or ""),
        results = {}
    }

    for _, edit in ipairs(EDITS) do
        local resources, resolveError = resolve_resources(edit)
        if not resources then
            table.insert(status.results, {
                resourceType = edit.resourceType,
                mode = edit.mode,
                path = path_string(edit.path),
                status = "error",
                error = resolveError or "unresolved"
            })
        else
            for _, resource in ipairs(resources) do
                local result = {
                    resourceType = edit.resourceType,
                    mode = edit.mode,
                    path = path_string(edit.path),
                    guid = tostring(resource and resource.guid or ""),
                    status = "pending",
                    error = ""
                }
                apply_one(edit, resource, result)
                table.insert(status.results, result)
            end
        end
    end

    local lines = {}
    table.insert(lines, "{")
    table.insert(lines, '  "schema": ' .. lua_string(status.schema) .. ',')
    table.insert(lines, '  "profile": ' .. lua_string(status.profile) .. ',')
    table.insert(lines, '  "gameVersion": ' .. lua_string(status.gameVersion) .. ',')
    table.insert(lines, '  "results": [')
    for i, result in ipairs(status.results) do
        local comma = (i < #status.results) and "," or ""
        table.insert(lines, '    {"resourceType":' .. lua_string(result.resourceType)
            .. ',"mode":' .. lua_string(result.mode)
            .. ',"path":' .. lua_string(result.path)
            .. ',"guid":' .. lua_string(result.guid)
            .. ',"status":' .. lua_string(result.status)
            .. ',"error":' .. lua_string(result.error) .. '}' .. comma)
    end
    table.insert(lines, '  ]')
    table.insert(lines, "}")

    io.export(@@EXPORT_PATH@@, table.concat(lines, "\\n"))

    local applied = 0
    local failed = 0
    for _, result in ipairs(status.results) do
        if result.status == "applied" then applied = applied + 1 end
        if result.status == "error" then failed = failed + 1 end
    end
    print(@@MOD_NAME@@ .. ": applied=" .. tostring(applied) .. " failed=" .. tostring(failed))
end

run()
"""


def _edit_table_entries(profile: Profile, db: TypeDatabase) -> List[str]:
    """Build the Lua table entry strings for each enabled edit."""
    entries: List[str] = []
    for edit in profile.enabled_edits():
        # Resolve the field path (validated against schema).
        lua_class = _resource_type_to_lua_class(edit.resource_type)
        resolution = resolve_path(db, lua_class, edit.path)
        if not resolution.ok:
            raise ValueError(
                "cannot generate Lua: path %r invalid for %s: %s"
                % (edit.path, edit.resource_type, resolution.error)
            )

        fields = [
            "resourceType = " + lua_string(edit.resource_type),
            "mode = " + lua_string(edit.target.mode),
            "path = " + lua_path_table(resolution.components),
        ]

        if edit.target.mode == "match" and edit.target.selector:
            selector = edit.target.selector
            selector_path = selector.get("field", "")
            selector_resolution = resolve_path(db, lua_class, selector_path)
            if not selector_resolution.ok:
                raise ValueError(
                    "cannot generate Lua: selector path %r invalid for %s: %s"
                    % (selector_path, edit.resource_type, selector_resolution.error)
                )
            fields.append(
                "selectorField = " + lua_path_table(selector_resolution.components)
            )
            fields.append(
                "selectorValue = "
                + lua_literal(selector.get("value"), selector_resolution.kind_label)
            )

        fields.append("value = " + lua_literal(edit.value, edit.schema_type))

        if edit.expected_original is not None:
            fields.append("hasExpected = true")
            fields.append(
                "expected = " + lua_literal(edit.expected_original, edit.schema_type)
            )
        else:
            fields.append("hasExpected = false")

        entries.append("{ " + ", ".join(fields) + " }")

    return entries


def _resource_type_to_lua_class(resource_type: str) -> str:
    return resource_type.replace("::", ".")


def generate_lua(
    profile: Profile,
    db: TypeDatabase,
    mod_id: str = "architect_lua_config_lab",
    export_path: Optional[str] = None,
) -> str:
    """Generate the deterministic ``mod.lua`` body for ``profile``."""
    edits_block = _edit_table_entries(profile, db)
    if not edits_block:
        edits_block_text = "{\n}"
    else:
        edits_block_text = "{\n    " + ",\n    ".join(edits_block) + "\n}"

    export_target = export_path or (mod_id + "/status.json")
    mod_name = mod_id

    return (
        _LUA_TEMPLATE
        .replace("@@MOD_NAME@@", lua_string(mod_name))
        .replace("@@PROFILE_NAME@@", lua_string(profile.name))
        .replace("@@EDITS_BLOCK@@", edits_block_text)
        .replace("@@EXPORT_PATH@@", lua_string(export_target))
    )


def modification_summary(profile: Profile, db: TypeDatabase) -> str:
    """Human-readable summary of the edits in a profile."""
    lines: List[str] = []
    lines.append("Profile: %s" % profile.name)
    if profile.description:
        lines.append("Description: %s" % profile.description)
    lines.append("")
    for edit in profile.enabled_edits():
        lines.append(edit.resource_type)
        lines.append("  target: %s" % edit.target.mode.upper())
        if edit.target.mode == "match" and edit.target.selector:
            sel = edit.target.selector
            lines.append(
                "  selector: %s == %r"
                % (sel.get("field"), sel.get("value"))
            )
        lines.append("  %s" % edit.path)
        lines.append("  schema: %s" % edit.schema_type)
        lines.append("  new value: %r" % edit.value)
        if edit.expected_original is not None:
            lines.append("  expected original: %r" % edit.expected_original)
        lines.append("  runtime evidence: %s" % edit.evidence_state)
        lines.append("")
    return "\n".join(lines).rstrip()
