"""EML mod packaging.

Builds a standalone EML patch mod directory using the *known-good* Architect
EML layout:

    <ModDir>/
        mod.json
        src/
            mod.lua
        profile.json
        generated_manifest.json

``profile.json`` is retained so the exact source of every generated mod is
known. ``generated_manifest.json`` is this tool's provenance file (not an EML
requirement).
"""

from __future__ import annotations

import json
import os
import re
from typing import Dict, Optional

from .lua_generator import generate_lua
from .profile import Profile, dumps
from .schema_model import TypeDatabase


def sanitize_id(name: str) -> str:
    """Derive a filesystem/EML-safe identifier from a profile name."""
    slug = re.sub(r"[^A-Za-z0-9_]+", "_", name.strip()).strip("_").lower()
    if not slug:
        slug = "profile"
    return slug


def default_mod_id(profile: Profile) -> str:
    return "lua_config_lab_" + sanitize_id(profile.name)


def build_mod_json(mod_id: str, profile: Profile) -> Dict:
    """The EML manifest, mirroring the known-good Architect ``mod.json``."""
    return {
        "id": mod_id,
        "name": profile.name or mod_id,
        "version": "1.0.0",
        "capabilities": ["patch", "export"],
        "description": profile.description or "Generated by Architect Lua Config Lab.",
    }


def choose_output_path(
    base_output_dir: str,
    folder_name: str,
    overwrite: bool = False,
) -> str:
    """Return a non-colliding output directory path.

    If the target exists and ``overwrite`` is False, a versioned folder
    (``name_v2``, ``name_v3``, ...) is chosen instead.
    """
    if overwrite:
        return os.path.join(base_output_dir, folder_name)
    candidate = os.path.join(base_output_dir, folder_name)
    if not os.path.isdir(candidate):
        return candidate
    version = 2
    while True:
        candidate = os.path.join(base_output_dir, "%s_v%d" % (folder_name, version))
        if not os.path.isdir(candidate):
            return candidate
        version += 1


def build_mod_directory(
    profile: Profile,
    db: TypeDatabase,
    base_output_dir: str,
    provenance: Dict,
    mod_id: Optional[str] = None,
    folder_name: Optional[str] = None,
    export_path: Optional[str] = None,
    overwrite: bool = False,
) -> str:
    """Write a complete EML mod directory and return its path.

    Returns the absolute path of the created directory.
    """
    mod_id = mod_id or default_mod_id(profile)
    folder_name = folder_name or sanitize_id(profile.name)

    target = choose_output_path(base_output_dir, folder_name, overwrite)
    src_dir = os.path.join(target, "src")
    os.makedirs(src_dir, exist_ok=True)

    lua_body = generate_lua(
        profile,
        db,
        mod_id=mod_id,
        export_path=export_path or (mod_id + "/status.json"),
    )

    # mod.json
    with open(os.path.join(target, "mod.json"), "w", encoding="utf-8") as handle:
        json.dump(build_mod_json(mod_id, profile), handle, indent=2, ensure_ascii=False)
        handle.write("\n")

    # src/mod.lua
    with open(os.path.join(src_dir, "mod.lua"), "w", encoding="utf-8") as handle:
        handle.write(lua_body)

    # profile.json (retained source of truth)
    with open(os.path.join(target, "profile.json"), "w", encoding="utf-8") as handle:
        handle.write(dumps(profile))
        handle.write("\n")

    # generated_manifest.json (provenance)
    with open(os.path.join(target, "generated_manifest.json"), "w", encoding="utf-8") as handle:
        json.dump(provenance, handle, indent=2, ensure_ascii=False)
        handle.write("\n")

    return target
